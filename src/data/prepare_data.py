"""
Data preparation script for CV Hackathon 2026.
Executes:
1. Parsing of cars_meta.mat -> data/classes.json
2. Parsing of cars_train_annos.mat -> 8,144 records with 0-based boxes
3. Stratified 80/20 train/validation split (6,515 train / 1,629 val) with seed 42
4. Export of JSON annotations and YOLOv8 vehicle detection dataset (images/labels/yaml)
"""

import json
import os
import shutil
from pathlib import Path
from typing import Any

from sklearn.model_selection import train_test_split

from src.data.parser import parse_annotations, parse_cars_meta


def create_yolo_dataset(
    train_records: list[dict[str, Any]],
    val_records: list[dict[str, Any]],
    yolo_dir: str,
) -> None:
    """
    Export dataset in Ultralytics YOLO format.
    Creates images and labels directories for train and val splits.
    """
    images_train_dir = os.path.join(yolo_dir, "images", "train")
    images_val_dir = os.path.join(yolo_dir, "images", "val")
    labels_train_dir = os.path.join(yolo_dir, "labels", "train")
    labels_val_dir = os.path.join(yolo_dir, "labels", "val")

    for d in [images_train_dir, images_val_dir, labels_train_dir, labels_val_dir]:
        os.makedirs(d, exist_ok=True)

    def process_split(
        records: list[dict[str, Any]], img_dest_dir: str, lbl_dest_dir: str
    ):
        filepath_list = []
        for rec in records:
            src_img = rec["file_path"]
            fname = rec["filename"]
            stem = Path(fname).stem
            dest_img = os.path.join(img_dest_dir, fname)
            dest_lbl = os.path.join(lbl_dest_dir, f"{stem}.txt")

            # Symlink image (fallback to copy if symlink fails)
            if not os.path.exists(dest_img):
                try:
                    os.symlink(src_img, dest_img)
                except OSError:
                    shutil.copyfile(src_img, dest_img)

            filepath_list.append(os.path.abspath(dest_img).replace("\\", "/"))

            # Write YOLO label format: <class_idx> <x_center> <y_center> <width> <height>
            # Single vehicle detection class (0 = vehicle)
            xc, yc, w, h = rec["bbox_yolo"]
            with open(dest_lbl, "w", encoding="utf-8") as f:
                f.write(f"0 {xc:.6f} {yc:.6f} {w:.6f} {h:.6f}\n")

        return filepath_list

    train_files = process_split(train_records, images_train_dir, labels_train_dir)
    val_files = process_split(val_records, images_val_dir, labels_val_dir)

    # Write file lists
    with open(os.path.join(yolo_dir, "train.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(train_files) + "\n")
    with open(os.path.join(yolo_dir, "val.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(val_files) + "\n")

    # Author dataset.yaml
    yolo_dir_abs = os.path.abspath(yolo_dir).replace("\\", "/")
    yaml_content = f"""# YOLOv8 Vehicle Detection Dataset Configuration
# Auto-generated by src.data.prepare_data
path: {yolo_dir_abs}
train: images/train
val: images/val

# Classes
nc: 1
names:
  0: vehicle
"""
    yaml_path = os.path.join(yolo_dir, "dataset.yaml")
    with open(yaml_path, "w", encoding="utf-8") as f:
        f.write(yaml_content)

    print(f"[YOLO] Dataset exported to: {yolo_dir}")
    print(f"       Train images/labels: {len(train_records)}")
    print(f"       Val images/labels:   {len(val_records)}")
    print(f"       Config YAML:         {yaml_path}")


def prepare_dataset(workspace_dir: str = "D:/CV", random_seed: int = 42) -> None:
    """
    Main orchestration routine for Phase 1 data preparation.
    """
    meta_path = os.path.join(
        workspace_dir, "Stanford Dataset", "car_devkit", "devkit", "cars_meta.mat"
    )
    train_annos_path = os.path.join(
        workspace_dir,
        "Stanford Dataset",
        "car_devkit",
        "devkit",
        "cars_train_annos.mat",
    )
    train_imgs_dir = os.path.join(
        workspace_dir, "Stanford Dataset", "cars_train", "cars_train"
    )

    data_dir = os.path.join(workspace_dir, "data")
    classes_json_path = os.path.join(data_dir, "classes.json")
    all_annos_path = os.path.join(data_dir, "all_train_annotations.json")
    train_annos_out = os.path.join(data_dir, "train_annotations.json")
    val_annos_out = os.path.join(data_dir, "val_annotations.json")
    yolo_dir = os.path.join(data_dir, "yolo")

    os.makedirs(data_dir, exist_ok=True)

    print("==================================================")
    print("STEP 1: Parsing cars_meta.mat into classes.json")
    print("==================================================")
    classes_meta = parse_cars_meta(meta_path, classes_json_path)
    print(f"Parsed {classes_meta['num_classes']} classes:")
    print(f"  Unique Makes:      {len(classes_meta['makes'])}")
    print(f"  Unique Years:      {len(classes_meta['years'])}")
    print(f"  Unique Body Types: {len(classes_meta['body_types'])}")
    print(f"  Saved metadata to: {classes_json_path}")

    print("\n==================================================")
    print("STEP 2: Parsing cars_train_annos.mat (8,144 records)")
    print("==================================================")
    all_records = parse_annotations(
        train_annos_path, train_imgs_dir, classes_meta, is_test=False
    )
    print(f"Parsed {len(all_records)} ground truth records.")
    with open(all_annos_path, "w", encoding="utf-8") as f:
        json.dump(all_records, f, indent=2)
    print(f"Saved full annotations to: {all_annos_path}")

    print("\n==================================================")
    print(f"STEP 3: Stratified 80/20 Split (Seed={random_seed})")
    print("==================================================")
    class_labels = [r["class_id_0"] for r in all_records]

    train_recs, val_recs = train_test_split(
        all_records, test_size=0.20, random_state=random_seed, stratify=class_labels
    )

    print(f"Train split size: {len(train_recs)} (Expected: 6515)")
    print(f"Val split size:   {len(val_recs)} (Expected: 1629)")
    assert len(train_recs) == 6515, (
        f"Expected 6515 train records, got {len(train_recs)}"
    )
    assert len(val_recs) == 1629, f"Expected 1629 val records, got {len(val_recs)}"

    # Verify all 196 classes exist in both splits
    train_classes = {r["class_id_0"] for r in train_recs}
    val_classes = {r["class_id_0"] for r in val_recs}
    print(f"Unique classes in train split: {len(train_classes)} / 196")
    print(f"Unique classes in val split:   {len(val_classes)} / 196")
    assert len(train_classes) == 196, "Train split does not cover all 196 classes!"
    assert len(val_classes) == 196, "Val split does not cover all 196 classes!"

    # Save splits
    with open(train_annos_out, "w", encoding="utf-8") as f:
        json.dump(train_recs, f, indent=2)
    with open(val_annos_out, "w", encoding="utf-8") as f:
        json.dump(val_recs, f, indent=2)
    print(f"Saved train annotations: {train_annos_out}")
    print(f"Saved val annotations:   {val_annos_out}")

    print("\n==================================================")
    print("STEP 4: Generating YOLO Detection Dataset")
    print("==================================================")
    create_yolo_dataset(train_recs, val_recs, yolo_dir)

    print("\n==================================================")
    print("DATA PREPARATION COMPLETED SUCCESSFULLY!")
    print("==================================================")


if __name__ == "__main__":
    prepare_dataset()
